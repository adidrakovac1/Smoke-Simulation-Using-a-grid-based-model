#!/usr/bin/env python3
"""Writes the three test meshes for the obstacle demo (docs/plan/EXECUTION_PLAN.md, P4.5):

    Integration/assets/cube.obj      closed box, 12 triangles
    Integration/assets/sphere.obj    closed sphere made of latitude / longitude bands
    Integration/assets/blanket.obj   open flat sheet (a "blanket"), a grid of triangles in the x-z plane

They are generated, not downloaded, so their origin and licence are clear. All faces are counter-clockwise when
seen from outside. Sizes do not matter: the program rescales every mesh to a unit size when it loads it.

    python tools/make_test_meshes.py
"""

import math
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "Integration" / "assets"


def write_obj(name, comment, vertices, faces):
    lines = [f"# {comment}", "# generated by tools/make_test_meshes.py", f"o {name}"]
    lines += [f"v {x:.6f} {y:.6f} {z:.6f}" for x, y, z in vertices]
    lines += ["f " + " ".join(str(i + 1) for i in face) for face in faces]
    path = OUT / f"{name}.obj"
    path.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"{path}: {len(vertices)} vertices, {len(faces)} faces")


def cube():
    v = [(x, y, z) for z in (-0.5, 0.5) for y in (-0.5, 0.5) for x in (-0.5, 0.5)]
    quads = [(0, 2, 3, 1), (4, 5, 7, 6), (0, 1, 5, 4), (2, 6, 7, 3), (0, 4, 6, 2), (1, 3, 7, 5)]
    write_obj("cube", "unit cube centred at the origin", v, quads)


def sphere(stacks=16, slices=32):
    v = [(0.0, 0.5, 0.0)]
    for s in range(1, stacks):
        phi = math.pi * s / stacks
        for t in range(slices):
            theta = 2.0 * math.pi * t / slices
            v.append((0.5 * math.sin(phi) * math.cos(theta), 0.5 * math.cos(phi), 0.5 * math.sin(phi) * math.sin(theta)))
    v.append((0.0, -0.5, 0.0))
    bottom = len(v) - 1
    ring = lambda s, t: 1 + (s - 1) * slices + (t % slices)
    faces = []
    for t in range(slices):
        faces.append((0, ring(1, t + 1), ring(1, t)))
        faces.append((bottom, ring(stacks - 1, t), ring(stacks - 1, t + 1)))
    for s in range(1, stacks - 1):
        for t in range(slices):
            faces.append((ring(s, t), ring(s, t + 1), ring(s + 1, t + 1), ring(s + 1, t)))
    write_obj("sphere", "sphere of diameter 1 centred at the origin", v, faces)


def blanket(cells=8):
    v = [(-0.5 + i / cells, 0.0, -0.5 + k / cells) for k in range(cells + 1) for i in range(cells + 1)]
    at = lambda i, k: k * (cells + 1) + i
    faces = []
    for k in range(cells):
        for i in range(cells):
            faces.append((at(i, k), at(i, k + 1), at(i + 1, k + 1)))
            faces.append((at(i, k), at(i + 1, k + 1), at(i + 1, k)))
    write_obj("blanket", "flat open sheet in the x-z plane, side 1", v, faces)


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    cube()
    sphere()
    blanket()
