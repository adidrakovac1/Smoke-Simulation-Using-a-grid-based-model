#!/usr/bin/env python3
"""Writes the meshes of the house scene (decision D22, docs/plan/OBSTACLES.md, section 6) into
Integration/assets/house/:

    house_floor.obj        floor slab, house_ground.obj grass around the house
    house_shell.obj        outer walls with window openings (drawn only: the solver box walls are already solid)
    house_glass.obj        window panes (drawn transparent), house_frames.obj window frames
    house_ceiling.obj      ceiling (drawn only; the panel can hide it to look in from above)
    house_inner_walls.obj  inner walls with doorways (drawn AND voxelized as solid obstacles)
    table.obj, chair.obj, sofa.obj, bed.obj, wardrobe.obj, shelf.obj, kitchen_counter.obj
    fan.obj                standing fan, blowing along +x
    source_marker.obj      small sphere that marks a smoke source

Everything is generated, not downloaded, so the origin and licence are clear. Unit: 1 metre.
Every mesh is a union of CLOSED boxes (or a closed sphere), all faces counter-clockwise seen from outside, so the
solver's flood-fill voxelizer (Solver/src/Voxelizer.cpp) fills them reliably; overlapping boxes are fine, because
the voxelizer floods from outside instead of counting crossings.

House coordinates are world coordinates: the inside of the house, which is exactly the solver box, is
x in [-6, 6], y in [0, 3], z in [-4.5, 4.5] (HouseScene uses the same numbers, kHouseMin / kHouseSize).
Furniture, the fan and the marker have their own origin: furniture and the fan stand on y = 0 and are centred in
x and z; the marker is centred at the origin.

    python tools/make_house_meshes.py
"""

import math
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "Integration" / "assets" / "house"

# Inside of the house = solver box (metres).
X0, X1 = -6.0, 6.0
Y0, Y1 = 0.0, 3.0
Z0, Z1 = -4.5, 4.5
WALL = 0.25      # inner and outer wall thickness: >= 2 cells even on the coarsest grid (0.10 m), OBSTACLES.md 5
DOOR_H = 2.1     # doorway height


class Mesh:
    def __init__(self):
        self.v = []
        self.f = []

    def add_box(self, x0, x1, y0, y1, z0, z1):
        """Closed axis-aligned box, faces counter-clockwise from outside (same order as make_test_meshes.cube)."""
        base = len(self.v)
        self.v += [(x, y, z) for z in (z0, z1) for y in (y0, y1) for x in (x0, x1)]
        quads = [(0, 2, 3, 1), (4, 5, 7, 6), (0, 1, 5, 4), (2, 6, 7, 3), (0, 4, 6, 2), (1, 3, 7, 5)]
        self.f += [tuple(base + i for i in q) for q in quads]

    def add_sphere(self, radius, stacks=12, slices=24):
        base = len(self.v)
        self.v.append((0.0, radius, 0.0))
        for s in range(1, stacks):
            phi = math.pi * s / stacks
            for t in range(slices):
                theta = 2.0 * math.pi * t / slices
                self.v.append((radius * math.sin(phi) * math.cos(theta), radius * math.cos(phi),
                               radius * math.sin(phi) * math.sin(theta)))
        self.v.append((0.0, -radius, 0.0))
        bottom = len(self.v) - 1
        ring = lambda s, t: base + 1 + (s - 1) * slices + (t % slices)
        for t in range(slices):
            self.f.append((base, ring(1, t + 1), ring(1, t)))
            self.f.append((bottom, ring(stacks - 1, t), ring(stacks - 1, t + 1)))
        for s in range(1, stacks - 1):
            for t in range(slices):
                self.f.append((ring(s, t), ring(s, t + 1), ring(s + 1, t + 1), ring(s + 1, t)))

    def write(self, name, comment):
        lines = [f"# {comment}", "# generated by tools/make_house_meshes.py (unit: metre)", f"o {name}"]
        lines += [f"v {x:.6f} {y:.6f} {z:.6f}" for x, y, z in self.v]
        lines += ["f " + " ".join(str(i + 1) for i in face) for face in self.f]
        path = OUT / f"{name}.obj"
        path.write_text("\n".join(lines) + "\n", encoding="ascii")
        xs, ys, zs = zip(*self.v)
        print(f"{path.name:24s} {len(self.v):5d} vertices {len(self.f):5d} faces   "
              f"size {max(xs) - min(xs):.2f} x {max(ys) - min(ys):.2f} x {max(zs) - min(zs):.2f} m")


def wall_along_x(m, z, xa, xb, doors):
    """Wall on the line z = const from x = xa to xb, with doorways [(x0, x1), ...] (lintel above each door)."""
    edges = [xa] + [e for d in sorted(doors) for e in d] + [xb]
    for i in range(0, len(edges), 2):
        if edges[i + 1] > edges[i]:
            m.add_box(edges[i], edges[i + 1], Y0, Y1, z - WALL / 2, z + WALL / 2)
    for d0, d1 in doors:
        m.add_box(d0, d1, DOOR_H, Y1, z - WALL / 2, z + WALL / 2)


def wall_along_z(m, x, za, zb, doors):
    """Wall on the line x = const from z = za to zb, with doorways [(z0, z1), ...]."""
    edges = [za] + [e for d in sorted(doors) for e in d] + [zb]
    for i in range(0, len(edges), 2):
        if edges[i + 1] > edges[i]:
            m.add_box(x - WALL / 2, x + WALL / 2, Y0, Y1, edges[i], edges[i + 1])
    for d0, d1 in doors:
        m.add_box(x - WALL / 2, x + WALL / 2, DOOR_H, Y1, d0, d1)


SILL, WIN_TOP = 0.9, 2.1   # window sill and top height
FRAME = 0.05               # window frame bar width


def outer_wall(wall, glass, frames, along, t0, t1, a, b, windows):
    """Outer wall from a to b along `along` ('x' or 'z'), thickness [t0, t1] across it, with windows
    [(w0, w1), ...]: full-height pieces between the windows, pieces below the sill and above the top, a glass
    pane in the middle of the thickness and a frame (four bars and a middle post) in each opening."""
    def box(m, u0, u1, y0, y1, v0, v1):
        if along == "x":
            m.add_box(u0, u1, y0, y1, v0, v1)
        else:
            m.add_box(v0, v1, y0, y1, u0, u1)
    edges = [a] + [e for w in sorted(windows) for e in w] + [b]
    for i in range(0, len(edges), 2):
        if edges[i + 1] > edges[i]:
            box(wall, edges[i], edges[i + 1], Y0, Y1, t0, t1)
    mid = 0.5 * (t0 + t1)
    for w0, w1 in windows:
        box(wall, w0, w1, Y0, SILL, t0, t1)
        box(wall, w0, w1, WIN_TOP, Y1, t0, t1)
        box(glass, w0, w1, SILL, WIN_TOP, mid - 0.01, mid + 0.01)
        box(frames, w0, w1, SILL, SILL + FRAME, t0, t1)
        box(frames, w0, w1, WIN_TOP - FRAME, WIN_TOP, t0, t1)
        box(frames, w0, w0 + FRAME, SILL, WIN_TOP, t0, t1)
        box(frames, w1 - FRAME, w1, SILL, WIN_TOP, t0, t1)
        c = 0.5 * (w0 + w1)
        box(frames, c - FRAME / 2, c + FRAME / 2, SILL, WIN_TOP, mid - 0.03, mid + 0.03)


def house():
    floor = Mesh()
    floor.add_box(X0 - WALL, X1 + WALL, Y0 - 0.15, Y0, Z0 - WALL, Z1 + WALL)
    floor.write("house_floor", "house: floor slab")

    ground = Mesh()  # grass around the house, seen through the windows
    ground.add_box(-40.0, 40.0, Y0 - 0.35, Y0 - 0.15, -40.0, 40.0)
    ground.write("house_ground", "ground plane around the house, 80 x 80 m")

    # Outer walls with windows (sill 0.9 m, top 2.1 m). Only drawn: the solver box walls are the house's outer
    # walls, so the windows are closed glass and the smoke stays inside.
    shell, glass, frames = Mesh(), Mesh(), Mesh()
    outer_wall(shell, glass, frames, "x", Z0 - WALL, Z0, X0, X1, [(-4.8, -3.4), (-1.8, -0.4), (3.0, 4.6)])  # south
    outer_wall(shell, glass, frames, "x", Z1, Z1 + WALL, X0, X1, [(-2.2, -0.8), (4.0, 5.4)])                # north
    outer_wall(shell, glass, frames, "z", X0 - WALL, X0, Z0 - WALL, Z1 + WALL, [(-2.6, -1.2), (1.8, 3.2)])  # west
    outer_wall(shell, glass, frames, "z", X1, X1 + WALL, Z0 - WALL, Z1 + WALL, [(-2.6, -1.2), (1.8, 3.2)])  # east
    shell.write("house_shell", "house: outer walls with window openings around the solver box [-6,6]x[0,3]x[-4.5,4.5]")
    glass.write("house_glass", "house: window panes (drawn transparent)")
    frames.write("house_frames", "house: window frames")

    ceiling = Mesh()
    ceiling.add_box(X0 - WALL, X1 + WALL, Y1, Y1 + 0.15, Z0 - WALL, Z1 + WALL)
    ceiling.write("house_ceiling", "house: ceiling slab")

    # Four rooms: living room (south-west), kitchen (south-east), bedroom (north-west), study (north-east).
    inner = Mesh()
    wall_along_x(inner, 0.5, X0, X1, doors=[(-3.6, -2.6), (2.8, 3.8)])  # south rooms | north rooms
    wall_along_z(inner, 1.0, Z0, 0.5 - WALL / 2, doors=[(-2.6, -1.0)])  # living room | kitchen (wide opening)
    wall_along_z(inner, 0.0, 0.5 + WALL / 2, Z1, doors=[])              # bedroom | study
    inner.write("house_inner_walls", "house: inner walls, 0.25 m thick, doorways 2.1 m high")


def furniture():
    m = Mesh()  # dining table 1.6 x 0.77 x 0.9
    m.add_box(-0.80, 0.80, 0.72, 0.77, -0.45, 0.45)
    for x in (-0.72, 0.65):
        for z in (-0.37, 0.30):
            m.add_box(x, x + 0.07, 0.0, 0.72, z, z + 0.07)
    m.write("table", "dining table")

    m = Mesh()  # chair, backrest towards +z
    m.add_box(-0.22, 0.22, 0.43, 0.48, -0.22, 0.22)
    for x in (-0.22, 0.18):
        for z in (-0.22, 0.18):
            m.add_box(x, x + 0.04, 0.0, 0.43, z, z + 0.04)
    m.add_box(-0.22, 0.22, 0.48, 0.95, 0.17, 0.22)
    m.write("chair", "chair, backrest towards +z")

    m = Mesh()  # sofa 2.0 x 0.87 x 0.9, backrest towards +z
    m.add_box(-1.00, 1.00, 0.00, 0.42, -0.45, 0.45)
    m.add_box(-1.00, 1.00, 0.42, 0.87, 0.25, 0.45)
    m.add_box(-1.00, -0.80, 0.42, 0.67, -0.45, 0.25)
    m.add_box(0.80, 1.00, 0.42, 0.67, -0.45, 0.25)
    m.write("sofa", "sofa, backrest towards +z")

    m = Mesh()  # double bed 1.6 x 2.0, headboard towards +z
    m.add_box(-0.80, 0.80, 0.00, 0.45, -1.00, 1.00)
    m.add_box(-0.80, 0.80, 0.00, 1.05, 0.92, 1.00)
    m.add_box(-0.70, 0.70, 0.45, 0.58, 0.55, 0.88)  # pillows
    m.write("bed", "double bed, headboard towards +z")

    m = Mesh()
    m.add_box(-0.60, 0.60, 0.0, 2.0, -0.30, 0.30)
    m.write("wardrobe", "wardrobe 1.2 x 2.0 x 0.6")

    m = Mesh()  # open bookshelf, back panel towards +z
    m.add_box(-0.50, 0.50, 0.0, 1.80, 0.14, 0.175)   # back
    m.add_box(-0.50, -0.47, 0.0, 1.80, -0.175, 0.14)  # sides
    m.add_box(0.47, 0.50, 0.0, 1.80, -0.175, 0.14)
    for y in (0.0, 0.45, 0.90, 1.35, 1.77):
        m.add_box(-0.47, 0.47, y, y + 0.03, -0.175, 0.14)
    m.write("shelf", "open bookshelf 1.0 x 1.8 x 0.35, back towards +z")

    m = Mesh()
    m.add_box(-1.20, 1.20, 0.0, 0.86, -0.30, 0.30)
    m.add_box(-1.225, 1.225, 0.86, 0.90, -0.325, 0.325)
    m.write("kitchen_counter", "kitchen counter 2.45 x 0.9 x 0.65")


def fan():
    # Standing fan. Blows along +x; the centre of its face is at (0.10, 1.10, 0.00) (HouseScene: kFanFaceOffset).
    m = Mesh()
    m.add_box(-0.20, 0.20, 0.00, 0.05, -0.20, 0.20)   # base
    m.add_box(-0.03, 0.03, 0.05, 1.00, -0.03, 0.03)   # pole
    m.add_box(-0.14, 0.04, 1.02, 1.18, -0.08, 0.08)   # motor
    for k in range(8):                                 # face: eight blades around the hub, in the y-z plane
        a = 2.0 * math.pi * k / 8
        cy, cz = 1.10 + 0.13 * math.sin(a), 0.13 * math.cos(a)
        m.add_box(0.04, 0.10, cy - 0.06, cy + 0.06, cz - 0.06, cz + 0.06)
    m.add_box(0.04, 0.11, 1.06, 1.14, -0.04, 0.04)    # hub
    m.write("fan", "standing fan, blows along +x, face centre (0.10, 1.10, 0)")

    m = Mesh()
    m.add_sphere(0.10)
    m.write("source_marker", "smoke source marker, sphere of diameter 0.2")


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    house()
    furniture()
    fan()
